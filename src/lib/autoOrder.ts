import { prisma } from './prisma'
import { generateOrderNumber } from './utils'

interface LowStockPart {
  id: string
  sku: string
  name: string
  quantity: number
  minQuantity: number
  costPrice: number
  vendorId: string | null
  autoOrderRule: {
    id: string
    reorderPoint: number
    reorderQuantity: number
    maxAutoOrderQty: number | null
    preferredVendorId: string | null
    isEnabled: boolean
  } | null
}

export async function checkLowStockParts(): Promise<LowStockPart[]> {
  const parts = await prisma.part.findMany({
    where: {
      isActive: true,
      OR: [
        // Parts below min quantity without auto-order rule
        {
          quantity: { lte: prisma.part.fields.minQuantity },
          autoOrderRule: null
        },
        // Parts with auto-order rule below reorder point
        {
          autoOrderRule: {
            isEnabled: true
          }
        }
      ]
    },
    include: {
      autoOrderRule: true
    }
  })

  // Filter to parts that are actually below their threshold
  return parts.filter(part => {
    if (part.autoOrderRule) {
      return part.quantity <= part.autoOrderRule.reorderPoint
    }
    return part.quantity <= part.minQuantity
  })
}

export async function createAutoOrderLog(partId: string, triggeredQuantity: number, orderQuantity: number) {
  return prisma.autoOrderLog.create({
    data: {
      partId,
      triggeredQuantity,
      orderQuantity,
      status: 'PENDING_APPROVAL'
    },
    include: {
      part: {
        include: {
          vendor: true,
          autoOrderRule: true
        }
      }
    }
  })
}

export async function approveAutoOrder(logId: string, userId: string) {
  const log = await prisma.autoOrderLog.findUnique({
    where: { id: logId },
    include: {
      part: {
        include: {
          vendor: true,
          autoOrderRule: true
        }
      }
    }
  })

  if (!log) {
    throw new Error('Auto order log not found')
  }

  if (log.status !== 'PENDING_APPROVAL') {
    throw new Error('This auto order has already been processed')
  }

  // Determine vendor
  const vendorId = log.part.autoOrderRule?.preferredVendorId || log.part.vendorId

  if (!vendorId) {
    throw new Error('No vendor configured for this part')
  }

  // Create order
  const order = await prisma.order.create({
    data: {
      orderNumber: generateOrderNumber(),
      vendorId,
      status: 'PENDING',
      totalAmount: log.orderQuantity * log.part.costPrice,
      isAutoGenerated: true,
      autoOrderLogId: log.id,
      notes: `Auto-generated order for low stock: ${log.part.name}`,
      items: {
        create: {
          partId: log.partId,
          quantity: log.orderQuantity,
          unitPrice: log.part.costPrice
        }
      }
    },
    include: {
      vendor: true,
      items: {
        include: { part: true }
      }
    }
  })

  // Update log status
  await prisma.autoOrderLog.update({
    where: { id: logId },
    data: {
      status: 'ORDER_CREATED',
      approvedById: userId,
      approvedAt: new Date()
    }
  })

  return order
}

export async function rejectAutoOrder(logId: string, userId: string, reason: string) {
  return prisma.autoOrderLog.update({
    where: { id: logId },
    data: {
      status: 'REJECTED',
      approvedById: userId,
      approvedAt: new Date(),
      rejectionReason: reason
    }
  })
}

export async function getPendingAutoOrders() {
  return prisma.autoOrderLog.findMany({
    where: {
      status: 'PENDING_APPROVAL'
    },
    include: {
      part: {
        include: {
          vendor: true,
          category: true
        }
      }
    },
    orderBy: { createdAt: 'desc' }
  })
}

export async function triggerAutoOrders() {
  const lowStockParts = await checkLowStockParts()
  const results = []

  for (const part of lowStockParts) {
    // Check if there's already a pending auto-order for this part
    const existingPending = await prisma.autoOrderLog.findFirst({
      where: {
        partId: part.id,
        status: 'PENDING_APPROVAL'
      }
    })

    if (existingPending) {
      continue // Skip if already has pending order
    }

    // Determine order quantity
    let orderQuantity = part.autoOrderRule?.reorderQuantity || (part.minQuantity * 2)

    // Apply max limit if set
    if (part.autoOrderRule?.maxAutoOrderQty) {
      orderQuantity = Math.min(orderQuantity, part.autoOrderRule.maxAutoOrderQty)
    }

    const log = await createAutoOrderLog(part.id, part.quantity, orderQuantity)
    results.push(log)
  }

  return results
}
